#!/contrib/Mamoudou.Ba/miniconda3/envs/mlaws2t/bin/python
'''
Operational Real-Time Forecast Stream Visualization Suite.
Ingests real-time forecast streams generated by generate_realtime_etss_bias_96h_forecast_stream.py
alongside historical ground observations prior to t0.
Produces a 3-panel operational verification/forecast chart with:
  - Panel 1: Total Water Level (Observed, AI Forecast, ETSS Baseline, ETSS Corrected, Astronomical Tide)
  - Panel 2: Pure Surge Residual (Observed Surge, AI Pivot Surge Forecast, ETSS Physical Surge, ETSS Corrected Surge)
  - Panel 3: Meteorology Guidance (Sustained Wind Speed, Wind Gusts, Atmospheric Pressure)
  - Side Panel: Rollout Stream Card with lead times, peak/min surges, and meteorological summaries.
'''

import os, sys, glob, warnings
warnings.filterwarnings('ignore')

import numpy as np
import pandas as pd

# Force headless Matplotlib execution
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.dates as mdates

# --- DIRECTORY AND PATH CONFIGURATIONS ---
STREAMS_DIR = '/contrib/Mamoudou.Ba/storm_surge/realtime_forecast_streams'
OBS_DIR = '/contrib/Mamoudou.Ba/storm_surge/'
CONFIG_FILE = '/contrib/Mamoudou.Ba/storm_surge/stations_config.csv'
if not os.path.exists(CONFIG_FILE):
    CONFIG_FILE = '/contrib/Mamoudou.Ba/storm_surge/all_stations_config.csv'

OUTPUT_DIR = '/contrib/Mamoudou.Ba/storm_surge/verification_plots'
os.makedirs(OUTPUT_DIR, exist_ok=True)

HINDCAST_HOURS = 24  # Historical observation window displayed prior to t0

def load_and_parse(file_path):
    df = pd.read_csv(file_path)
    time_candidates = ['timestamp', 'timestamp_gui', 'dt', 'datetime', 'date_time', 'valid_time', 'time', 'date']
    t_col = None
    for c in time_candidates:
        if c in df.columns:
            t_col = c
            break
    if not t_col:
        matched = [c for c in df.columns if any(k in c.lower() for k in ['time', 'date', 'dt'])]
        if matched:
            t_col = matched[0]

    if not t_col:
        raise KeyError(f"No valid datetime column found in {file_path}. Columns: {list(df.columns)}")

    df['dt'] = pd.to_datetime(df[t_col], errors='coerce', format='mixed')
    if df['dt'].dt.tz is not None:
        df['dt'] = df['dt'].dt.tz_localize(None)
    df['dt'] = df['dt'].dt.round('h')
    return df.dropna(subset=['dt'])

# --- 1. RESOLVE CSV FORECAST STREAM FILES ---
stream_files = sorted(glob.glob(os.path.join(STREAMS_DIR, "realtime_*_96h_forecast_*.csv")))

if not stream_files:
    print(f"❌ No forecast stream CSV files found in {STREAMS_DIR}")
    sys.exit(1)

# Allow optional command line filter: python script.py 8670870
if len(sys.argv) > 1 and not sys.argv[1].startswith('-'):
    target_sid = str(sys.argv[1]).strip()
    stream_files = [f for f in stream_files if target_sid in os.path.basename(f)]
    print(f"🎯 Filtered for station: {target_sid} ({len(stream_files)} file(s) matched)")

print(f"📊 Processing {len(stream_files)} forecast stream CSV file(s) in {STREAMS_DIR}")

station_name_map = {}
if os.path.exists(CONFIG_FILE):
    df_cfg = pd.read_csv(CONFIG_FILE, dtype={'station_id': str})
    for _, r in df_cfg.iterrows():
        sid = str(r['station_id']).strip()
        sname = str(r['station_name']).strip().replace('"', '').replace(',', '').replace(' ', '_')
        station_name_map[sid] = sname

# --- 2. ITERATE OVER EACH REAL-TIME FORECAST STREAM ---
for csv_path in stream_files:
    try:
        df_stream = load_and_parse(csv_path)
        if df_stream.empty:
            continue

        STATION_ID = str(df_stream['station_id'].iloc[0]).strip()
        STATION_NAME = str(df_stream['station_name'].iloc[0]).strip() if 'station_name' in df_stream.columns else station_name_map.get(STATION_ID, f"Station_{STATION_ID}")

        origin_str = df_stream['forecast_origin'].iloc[0]
        t0 = pd.to_datetime(origin_str)
        if t0.tz is not None:
            t0 = t0.tz_localize(None)

        df_stream = df_stream.set_index('dt').sort_index()
        forecast_lead_hours = len(df_stream)

        print("\n" + "=" * 80)
        print(f"🎨 PLOTTING REAL-TIME STREAM FOR: {STATION_NAME} ({STATION_ID})")
        print(f"   > Origin (t0): {t0} | Rollout Horizon: {forecast_lead_hours}h")
        print(f"   > Source: {os.path.basename(csv_path)}")
        print("=" * 80)

        # --- 3. INGEST HISTORICAL GROUND TRUTH PRIOR TO t0 ---
        candidate_obs_files = [
            os.path.join(OBS_DIR, f'realtime_obs_{STATION_ID}_2026.csv'),
            os.path.join(OBS_DIR, f'obs_training_{STATION_ID}_2026.csv'),
            os.path.join(OBS_DIR, f'obs_{STATION_ID}_wl_only.csv'),
            os.path.join(OBS_DIR, f'obs_training_{STATION_ID}.csv')
        ]

        obs_file = next((cand for cand in candidate_obs_files if os.path.exists(cand)), None)

        t_start = t0 - pd.Timedelta(hours=HINDCAST_HOURS)
        hindcast_idx = pd.date_range(start=t_start, end=t0, freq='h')
        hindcast_df = pd.DataFrame(index=hindcast_idx)

        # Ingest tide & weather from GFS spatial dataset if available
        gfs_spatial_file = os.path.join(OBS_DIR, f'test_gfs_etss_spatial_data_{STATION_ID}_2026.csv')
        if not os.path.exists(gfs_spatial_file):
            gfs_spatial_file = os.path.join(OBS_DIR, f'test_gfs_etss_data_{STATION_ID}_2026.csv')

        df_g = None
        if os.path.exists(gfs_spatial_file):
            df_g = load_and_parse(gfs_spatial_file).drop_duplicates(subset=['dt']).set_index('dt').sort_index()
            t_cols = [c for c in df_g.columns if 'tide' in c.lower()]
            hindcast_df['etss_tide'] = df_g[t_cols[0]].reindex(hindcast_df.index).ffill().bfill().fillna(0.0) if t_cols else 0.0

            # Hindcast weather from GFS
            for col_cand in ['wind_speed_gui', 'wind_speed']:
                if col_cand in df_g.columns:
                    hindcast_df['wind_speed'] = df_g[col_cand].reindex(hindcast_df.index).ffill().bfill()
                    break
            for col_cand in ['wind_gust_gui', 'wind_gust']:
                if col_cand in df_g.columns:
                    hindcast_df['wind_gust'] = df_g[col_cand].reindex(hindcast_df.index).ffill().bfill()
                    break
            for col_cand in ['air_pressure_gui', 'air_pressure']:
                if col_cand in df_g.columns:
                    hindcast_df['air_pressure'] = df_g[col_cand].reindex(hindcast_df.index).ffill().bfill()
                    break
        else:
            hindcast_df['etss_tide'] = 0.0

        has_valid_obs = False
        if obs_file:
            print(f"   > Ingesting Hindcast Truth from: {os.path.basename(obs_file)}")
            df_obs_raw = load_and_parse(obs_file).drop_duplicates(subset=['dt']).set_index('dt').sort_index()
            if 'water_level' in df_obs_raw.columns:
                s_wl = df_obs_raw['water_level'].replace(99999.0, np.nan).reindex(hindcast_df.index)
                if not s_wl.dropna().empty:
                    hindcast_df['water_level'] = s_wl.interpolate(method='time').ffill().bfill()
                    raw_s = hindcast_df['water_level'] - hindcast_df['etss_tide']
                    hindcast_df['surge_residual'] = raw_s.rolling(window=12, center=True, min_periods=1).mean().ffill().bfill()
                    has_valid_obs = True

            # Overlay observed meteorology if present
            if 'wind_speed' in df_obs_raw.columns and df_obs_raw['wind_speed'].notna().sum() > 5:
                hindcast_df['wind_speed'] = df_obs_raw['wind_speed'].reindex(hindcast_df.index).interpolate().ffill().bfill()
            if 'wind_gust' in df_obs_raw.columns and df_obs_raw['wind_gust'].notna().sum() > 5:
                hindcast_df['wind_gust'] = df_obs_raw['wind_gust'].reindex(hindcast_df.index).interpolate().ffill().bfill()
            if 'air_pressure' in df_obs_raw.columns and df_obs_raw['air_pressure'].notna().sum() > 5:
                hindcast_df['air_pressure'] = df_obs_raw['air_pressure'].reindex(hindcast_df.index).interpolate().ffill().bfill()

        # Forecast series
        tide_stream = df_stream['etss_tide_ft'] if 'etss_tide_ft' in df_stream.columns else df_stream['etss_tide']
        surge_stream = df_stream['pivot_surge_forecast_ft'] if 'pivot_surge_forecast_ft' in df_stream.columns else df_stream['etss_corrected_surge_ft']
        etss_surge_stream = df_stream['etss_surge_ft'] if 'etss_surge_ft' in df_stream.columns else df_stream['etss_surge']
        etss_wl_stream = etss_surge_stream + tide_stream
        piv_wl_stream = df_stream['pivot_total_water_level_ft'] if 'pivot_total_water_level_ft' in df_stream.columns else (surge_stream + tide_stream)

        # ETSS Corrected (continuous stream or bias-shifted)
        if 'etss_corrected_surge_ft' in df_stream.columns:
            etss_surge_corrected = df_stream['etss_corrected_surge_ft']
            etss_twl_corrected = df_stream['etss_corrected_twl_ft']
            mean_bias = float((etss_surge_stream - etss_surge_corrected).mean())
        else:
            mean_bias = float((etss_surge_stream - surge_stream).mean())
            etss_surge_corrected = etss_surge_stream - mean_bias
            etss_twl_corrected = etss_surge_corrected + tide_stream

        # --- 4. 3-PANEL FIGURE RENDERING WITH METEOROLOGY ---
        fig = plt.figure(figsize=(23, 14))
        gs = matplotlib.gridspec.GridSpec(3, 2, width_ratios=[0.76, 0.24], height_ratios=[1.8, 1.5, 1.1], hspace=0.18, wspace=0.08)
        ax1 = fig.add_subplot(gs[0, 0])
        ax2 = fig.add_subplot(gs[1, 0], sharex=ax1)
        ax3 = fig.add_subplot(gs[2, 0], sharex=ax1)
        ax_stat = fig.add_subplot(gs[:, 1])
        ax_stat.axis('off')

        x_min = t_start
        x_max = df_stream.index.max() + pd.Timedelta(hours=1)
        ax1.set_xlim(x_min, x_max)

        # === PANEL 1: TOTAL WATER LEVEL (FT) ===
        if has_valid_obs:
            ax1.plot(hindcast_df.index, hindcast_df['water_level'], label='Observed Total Water (Truth)', color='#2c3e50', linewidth=2.5, zorder=5)
            ax1.plot(hindcast_df.index, hindcast_df['etss_tide'], label='Astronomical Tide (Historical)', color='#7f8c8d', linestyle='-', linewidth=1.0, alpha=0.3, zorder=2)
        else:
            if 'etss_tide' in hindcast_df.columns and not (hindcast_df['etss_tide'] == 0.0).all():
                ax1.plot(hindcast_df.index, hindcast_df['etss_tide'], label='Astronomical Tide (Historical)', color='#7f8c8d', linestyle='-', linewidth=1.0, alpha=0.3, zorder=2)

        ax1.plot(df_stream.index, piv_wl_stream, label=f'AI Chrono Rollout Forecast ({forecast_lead_hours}h)', color='#e67e22', linewidth=3.0, zorder=4)
        ax1.plot(df_stream.index, etss_wl_stream, label='ETSS Physics Forecast Baseline', color='#e74c3c', linestyle=':', linewidth=1.5, alpha=0.85, zorder=3)
        ax1.plot(df_stream.index, etss_twl_corrected, label='ETSS TWL Corrected', color='#008080', linestyle='--', linewidth=2.0, alpha=0.95, zorder=6)
        ax1.plot(df_stream.index, tide_stream, label='Astronomical Tide Guidance', color='#34495e', linestyle=':', linewidth=1.2, alpha=0.6, zorder=2)

        ax1.axvline(x=t0, color='#000000', linestyle='--', linewidth=2.0, alpha=0.85, zorder=7)
        y_lim1 = ax1.get_ylim()
        ax1.text(t0, y_lim1[1] * 0.92, '  FORECAST ORIGIN (t₀)', color='#000000', fontweight='bold', fontsize=10)

        ax1.set_title(f"Operational Deep Learning Storm Surge Forecast Suite: {STATION_NAME} ({STATION_ID}) | Lead: {forecast_lead_hours}h", fontsize=13, fontweight='bold', pad=12)
        ax1.set_ylabel("Total Water Level Scale (ft)", fontsize=10, labelpad=10)
        ax1.grid(True, linestyle=':', alpha=0.5, color='#bdc3c7')
        ax1.legend(loc='upper right', frameon=True, facecolor='#ffffff', edgecolor='#eceff1', fontsize=9, ncol=2)

        # === PANEL 2: METEOROLOGICAL SURGE RESIDUAL (FT) ===
        if has_valid_obs:
            ax2.plot(hindcast_df.index, hindcast_df['surge_residual'], label='Observed Surge Residual (Filtered)', color='#2c3e50', linewidth=2.5, zorder=5)

        ax2.plot(df_stream.index, surge_stream, label='AI Chrono Pivot Surge Forecast', color='#e67e22', linewidth=3.0, zorder=4)
        ax2.plot(df_stream.index, etss_surge_stream, label='ETSS Physics Baseline Model', color='#e74c3c', linestyle=':', linewidth=1.5, alpha=0.85, zorder=3)
        ax2.plot(df_stream.index, etss_surge_corrected, label='ETSS Surge Corrected', color='#008080', linestyle='--', linewidth=2.0, alpha=0.95, zorder=6)

        ax2.axvline(x=t0, color='#000000', linestyle='--', linewidth=2.0, alpha=0.85, zorder=7)
        ax2.set_ylabel("Surge Residual Elevation (ft)", fontsize=10, labelpad=10)
        ax2.grid(True, linestyle=':', alpha=0.5, color='#bdc3c7')
        ax2.legend(loc='upper right', frameon=True, facecolor='#ffffff', edgecolor='#eceff1', fontsize=9, ncol=2)

        # === PANEL 3: METEOROLOGY & WIND GUIDANCE (KTS & HPA) ===
        # Wind Speed & Gusts (Left Axis)
        ws_col = 'wind_speed_kts' if 'wind_speed_kts' in df_stream.columns else ('wind_speed' if 'wind_speed' in df_stream.columns else None)
        wg_col = 'wind_gust_kts' if 'wind_gust_kts' in df_stream.columns else ('wind_gust' if 'wind_gust' in df_stream.columns else None)
        ap_col = 'air_pressure_hPa' if 'air_pressure_hPa' in df_stream.columns else ('air_pressure' if 'air_pressure' in df_stream.columns else None)

        # Plot Hindcast Wind if available
        if 'wind_speed' in hindcast_df.columns and hindcast_df['wind_speed'].notna().sum() > 0:
            ax3.plot(hindcast_df.index, hindcast_df['wind_speed'], color='#34495e', linewidth=1.6, alpha=0.6, label='Wind Speed (Hindcast)')
        if 'wind_gust' in hindcast_df.columns and hindcast_df['wind_gust'].notna().sum() > 0:
            ax3.plot(hindcast_df.index, hindcast_df['wind_gust'], color='#c0392b', linestyle='--', linewidth=1.3, alpha=0.6, label='Wind Gust (Hindcast)')

        # Plot Forecast Guidance Wind
        if ws_col:
            ax3.plot(df_stream.index, df_stream[ws_col], color='#2c3e50', linewidth=2.2, label='GFS Wind Speed Guidance')
        if wg_col:
            ax3.plot(df_stream.index, df_stream[wg_col], color='#e74c3c', linestyle='--', linewidth=1.8, label='GFS Wind Gust Guidance')

        ax3.axvline(x=t0, color='#000000', linestyle='--', linewidth=2.0, alpha=0.85, zorder=7)
        ax3.set_ylabel("Wind (kts)", fontsize=10, labelpad=10, fontweight='bold', color='#2c3e50')
        ax3.set_xlabel("Timeline Partition (Hourly UTC)", fontsize=10, labelpad=10)
        ax3.set_ylim(bottom=0)
        ax3.grid(True, linestyle=':', alpha=0.5, color='#bdc3c7')
        ax3.legend(loc='upper left', frameon=True, facecolor='#ffffff', edgecolor='#eceff1', fontsize=8.5, ncol=2)

        # Atmospheric Pressure (Right Twin Axis)
        has_pres_fcst = ap_col and df_stream[ap_col].notna().sum() > 0
        has_pres_hind = 'air_pressure' in hindcast_df.columns and hindcast_df['air_pressure'].notna().sum() > 0

        if has_pres_fcst or has_pres_hind:
            ax3_p = ax3.twinx()
            if has_pres_hind:
                ax3_p.plot(hindcast_df.index, hindcast_df['air_pressure'], color='#8e44ad', linestyle='-.', linewidth=1.3, alpha=0.5, label='MSLP (Hindcast)')
            if has_pres_fcst:
                ax3_p.plot(df_stream.index, df_stream[ap_col], color='#8e44ad', linestyle='-.', linewidth=1.8, label='GFS Pressure Guidance')

            ax3_p.set_ylabel("Pressure (hPa)", fontsize=10, labelpad=10, color='#8e44ad', fontweight='bold')
            ax3_p.grid(False)
            ax3_p.legend(loc='upper right', frameon=True, facecolor='#ffffff', edgecolor='#eceff1', fontsize=8.5)

        fig.autofmt_xdate()

        # === SIDE PANEL: ROLLOUT STREAM CARD ===
        peak_surge = surge_stream.max()
        min_surge = surge_stream.min()
        peak_surge_dt = df_stream.index[surge_stream.argmax()].strftime('%m/%d %H:%MZ')
        min_surge_dt = df_stream.index[surge_stream.argmin()].strftime('%m/%d %H:%MZ')

        peak_wl = piv_wl_stream.max()
        peak_wl_dt = df_stream.index[piv_wl_stream.argmax()].strftime('%m/%d %H:%MZ')

        wind_max = df_stream[ws_col].max() if ws_col else np.nan
        gust_max = df_stream[wg_col].max() if wg_col else np.nan
        press_min = df_stream[ap_col].min() if ap_col else np.nan

        stat_card_text = (
            f"   REAL-TIME STREAM CARD\n"
            f"=========================\n"
            f" Station Target: {STATION_ID}\n"
            f" Location: {STATION_NAME}\n"
            f" Forecast Origin (t₀):\n"
            f"   > {t0.strftime('%Y-%m-%d %H:%MZ')}\n"
            f" Rollout Lead: +{forecast_lead_hours} Hours\n\n"
            f" [1] SURGE RESIDUAL PEAKS\n"
            f" -----------------------\n"
            f" * Max AI Surge: {peak_surge:+.3f} ft\n"
            f"   @ {peak_surge_dt}\n"
            f" * Min AI Surge: {min_surge:+.3f} ft\n"
            f"   @ {min_surge_dt}\n"
            f" * Mean ETSS Bias: {mean_bias:+.3f} ft\n\n"
            f" [2] WATER LEVEL EXTREMES\n"
            f" -----------------------\n"
            f" * Peak Total Water: {peak_wl:+.3f} ft\n"
            f"   @ {peak_wl_dt}\n\n"
            f" [3] GFS GUIDANCE EXTREMES\n"
            f" -----------------------\n"
            f" * Max Sustained Wind: {wind_max:.1f} kts\n"
            f" * Max Peak Gust: {gust_max:.1f} kts\n"
            f" * Min Sea-Level Press: {press_min:.1f} hPa\n\n"
            f" Operational Status:\n"
            f"   * Real-Time Forecast Active\n"
            f"   * Model: 4-Quad GFS + ETSS"
        )

        ax_stat.text(0.05, 0.95, stat_card_text, transform=ax_stat.transAxes,
                     fontsize=9.2, verticalalignment='top', fontname='monospace',
                     bbox=dict(boxstyle='round,pad=0.6', facecolor='#f8f9fa', edgecolor='#eceff1', linewidth=1.0))

        plot_out = os.path.join(OUTPUT_DIR, f"realtime_stream_forecast_plot_{STATION_ID}_{t0.strftime('%Y%m%d_%H%M')}.png")
        plt.savefig(plot_out, dpi=200, bbox_inches='tight')
        print(f"💾 Operational chart successfully exported ➔ {plot_out}")

        plt.close('all')
        fig.clear()

    except Exception as err:
        print(f"❌ Error rendering plot for {csv_path}: {err}")
        continue

print("\n🎉 Real-Time Stream Visualization Protocol Complete.")
